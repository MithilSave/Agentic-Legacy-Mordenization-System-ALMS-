def render_service(service_name: str, models: List[Dict], endpoints: List[Dict]) -> str:
    """Render a FastAPI service from template.

    Args:
        service_name: Name of the service (e.g., 'user-service')
        models: List of model definitions
        endpoints: List of endpoint definitions

    Returns:
        Generated Python source code string
    """
    env = Environment(loader=BaseLoader())
    template = env.from_string(FASTAPI_SERVICE_TEMPLATE)

    code = template.render(
        service_name=service_name,
        models=models,
        endpoints=endpoints,
    )

    return code


def render_tests(service_name: str, test_cases: List[Dict]) -> str:
    """Render pytest test suite from template."""
    env = Environment(loader=BaseLoader())
    template = env.from_string(PYTEST_TEMPLATE)

    code = template.render(
        service_name=service_name,
        test_cases=test_cases,
    )

    return code


