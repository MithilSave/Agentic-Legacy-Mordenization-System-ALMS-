def format_code(code: str) -> str:
    """Apply black and isort formatting to generated code.

    Falls back to original code if formatters aren't available.
    """
    formatted = code

    # Apply isort
    try:
        import isort
        formatted = isort.code(formatted)
    except ImportError:
        logger.warning("isort not available, skipping import sorting")

    # Apply black
    try:
        import black
        mode = black.Mode(line_length=100)
        formatted = black.format_str(formatted, mode=mode)
    except ImportError:
        logger.warning("black not available, skipping formatting")
    except Exception as e:
        logger.warning(f"black formatting failed: {e}")

    return formatted


def validate_syntax(code: str) -> bool:
    """Validate Python syntax using py_compile.

    Per CONTEXT.md: py_compile gate before Test-Gen handoff.
    """
    with tempfile.NamedTemporaryFile(mode="w", suffix=".py", delete=False, encoding="utf-8") as f:
        f.write(code)
        f.flush()
        temp_path = f.name

    try:
        py_compile.compile(temp_path, doraise=True)
        return True
    except py_compile.PyCompileError as e:
        logger.error(f"Syntax validation failed: {e}")
        return False
    finally:
        os.unlink(temp_path)
